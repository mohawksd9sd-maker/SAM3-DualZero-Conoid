"""Proton decay, rare-decay leptoquark bound, n-nbar and seesaw checks (docs 55, 57).

Baryon number in the spectral Pati-Salam model
----------------------------------------------
Give every field its SU(4) "index number" F = (#upper 4 indices) - (#lower):
F_L in 4: F=+1;  F_R as a left-handed 4bar: F=-1;  phi (1,2,2): 0;
Delta_R in 4: +1;  Sigma (1,1,15): 0;  gauge bosons: 0.
Any SU(4) invariant built only with delta-contractions has F = 0.  Only an
epsilon_{ABCD} contraction changes F (by +-4).  Every component of a 4 has
B - L = X with X(quark) = 1/3, X(lepton) = -1, so
        B = (F + X)/4,          L = (F - 3X)/4
reproduce B = 1/3, 0 and L = 0, 1 for quark and lepton components.  The
vev of Delta_R sits in the lepton component (B = 0), so it breaks L and B-L
but not B.  Therefore: if the Lagrangian has no epsilon_{ABCD} term, B is
exactly conserved in perturbation theory, also after m_R breaking.

The spectral action Tr f(D_A/Lambda) and the fermionic action <J psi, D_A psi>
are traces / bilinears of matrices acting on H_F: only delta-contractions of
SU(4) indices occur.  So no epsilon term is generated at Lambda, and because
U(1)_F is a symmetry of the classical action that is non-anomalous under SU(4)
(vector-like) the RG flow cannot generate one either.  The only B-violation
left is SU(2)_L / SU(2)_R instantons (Delta B = 3, rate ~ exp(-16 pi^2/g^2)),
which cannot destroy a single proton.
"""

from __future__ import annotations

import math
from fractions import Fraction as Fr
from typing import Dict, List, Tuple

HBAR_GEV_S = 6.582119569e-25
SEC_PER_YEAR = 3.15576e7

# ------------------------------------------------------------------ B bookkeeping

# component-level charges: (F, X) for each SU(4)-index component type
COMPONENTS = {
    "q (F_L/Delta, colour)": (1, Fr(1, 3)),
    "l (F_L/Delta, lepton)": (1, Fr(-1)),
    "qbar (F_R, colour)": (-1, Fr(-1, 3)),
    "lbar (F_R, lepton)": (-1, Fr(1)),
}


def B_of(F: int, X: Fr) -> Fr:
    return (Fr(F) + X) / 4


def L_of(F: int, X: Fr) -> Fr:
    return (Fr(F) - 3 * X) / 4


def operator_delta_B(components: List[Tuple[int, Fr]]) -> Fr:
    return sum((B_of(F, X) for F, X in components), Fr(0))


# The operators that can appear (by contraction type) and their Delta B.
OPERATORS = {
    # delta-contracted (spectral-action type)
    "Dirac Yukawa F_L phi F_R (top=nu_D)": [(1, Fr(1, 3)), (-1, Fr(-1, 3))],
    "Majorana F_R F_R Delta Delta, nu_R nu_R <Delta_l>^2": [(-1, Fr(1)), (-1, Fr(1)), (1, Fr(-1)), (1, Fr(-1))],
    "leptoquark current qbar gamma l X_mu (X carries F=0, X=4/3)": [(-1, Fr(-1, 3)), (1, Fr(-1)), (0, Fr(4, 3))],
    "Delta_3 coupling u^c e^c Delta_q <Delta_l> (from F_R F_R Delta Delta)": [(-1, Fr(-1, 3)), (-1, Fr(1)), (1, Fr(1, 3)), (1, Fr(-1))],
    # epsilon-contracted (NOT generated by a trace; allowed in a generic PS Lagrangian)
    "epsilon Delta^4  (qqq l)": [(1, Fr(1, 3))] * 3 + [(1, Fr(-1))],
    "epsilon F_L F_L Delta Delta -> qq Delta_q <Delta_l>": [(1, Fr(1, 3)), (1, Fr(1, 3)), (1, Fr(1, 3)), (1, Fr(-1))],
    "d=6 qqql (epsilon F_L^3 F_L)": [(1, Fr(1, 3))] * 3 + [(1, Fr(-1))],
}


def operator_table() -> Dict[str, Dict[str, object]]:
    out = {}
    for name, comps in OPERATORS.items():
        F = sum(c[0] for c in comps)
        out[name] = {"Delta_F": F, "Delta_B": operator_delta_B(comps), "epsilon": abs(F) == 4}
    return out


# ------------------------------------------------------------------ proton lifetime


def proton_lifetime_years(coeff_GeV_minus2: float, W0_GeV2: float = 0.131, chirality_factor: float = 5.0) -> float:
    """tau(p -> e+ pi0) for an effective d=6 operator with coefficient C.

    Gamma = m_p/(32 pi) (1 - m_pi^2/m_p^2)^2 |C|^2 |W0|^2 * chirality_factor,
    W0 = <pi0|(ud)u|p> ~ -0.131 GeV^2 (lattice, Aoki et al. PRD 96 (2017)
    014506); chirality_factor ~ 1 + (1+|V_ud|^2)^2 ~ 5 for SU(5)-like
    structure.  Order-of-magnitude estimate (factor ~3 in tau).
    """
    mp, mpi = 0.938272, 0.134977
    G = mp / (32 * math.pi) * (1 - mpi ** 2 / mp ** 2) ** 2 * coeff_GeV_minus2 ** 2 * W0_GeV2 ** 2 * chirality_factor
    return HBAR_GEV_S / G / SEC_PER_YEAR


SUPERK_P_EPI0_YEARS = 2.4e34  # Super-K, PRD 102 (2020) 112011, 90% CL
SHORT_DISTANCE_ENHANCEMENT = 2.5  # A_R ~ 2.5 (long+short distance), standard


def generic_d6_lifetime(M_GeV: float, alpha_U_inv: float, kappa: float = 1.0) -> float:
    """Lifetime if a B-violating d=6 operator kappa * g_U^2 / M^2 existed."""
    gU2 = 4 * math.pi / alpha_U_inv
    C = kappa * SHORT_DISTANCE_ENHANCEMENT * gU2 / M_GeV ** 2
    return proton_lifetime_years(C)


def kappa_max(M_GeV: float, alpha_U_inv: float) -> float:
    """Largest kappa allowed by Super-K (tau scales as kappa^-2)."""
    return math.sqrt(generic_d6_lifetime(M_GeV, alpha_U_inv, 1.0) / SUPERK_P_EPI0_YEARS)


# ------------------------------------------------------------------ leptoquark / rare decays

KL_MUE_BOUND_TEV = 1400.0  # Valencia-Willenbrock PRD 50 (1994) 6843, permutation mixing
GENERAL_MIXING_BOUND_TEV = 86.0  # Smirnov, MPLA 33 (2018) 1850019, general mixing
NNBAR_FREE_S = 0.86e8  # ILL, Baldo-Ceolin et al. 1994
NNBAR_BOUND_S = 4.7e8  # Super-K 2021, PRD 103 012008 (bound-neutron converted)


def leptoquark_mass_estimate(m_R: float, g4: float) -> Dict[str, float]:
    """M_X ~ g_4 v_R / sqrt(2) with v_R ~ m_R / g_R ~ m_R (O(1) factors stated)."""
    return {"M_X_GeV_order": m_R, "M_X_low_GeV": 0.3 * m_R, "M_X_high_GeV": 3.0 * m_R}


def rare_decay_check(m_R: float) -> Dict[str, object]:
    lo = 0.3 * m_R / 1e3
    return {
        "M_X_TeV_lowest_estimate": lo,
        "KL_mue_bound_TeV": KL_MUE_BOUND_TEV,
        "general_mixing_bound_TeV": GENERAL_MIXING_BOUND_TEV,
        "margin_orders_of_magnitude": math.log10(lo / KL_MUE_BOUND_TEV),
        "passes": lo > KL_MUE_BOUND_TEV,
    }


# ------------------------------------------------------------------ seesaw

V_EW = 246.22
SQRT_DM2_ATM_EV = 0.0501  # sqrt(2.51e-3 eV^2), NuFIT 5.x/6.0


def seesaw(y_at_mR: float, M_N_GeV: float) -> Dict[str, float]:
    mD = y_at_mR * V_EW / math.sqrt(2)
    m_nu_eV = mD ** 2 / M_N_GeV * 1e9
    return {"m_D_GeV": mD, "M_N_GeV": M_N_GeV, "m_nu3_eV": m_nu_eV,
            "M_N_needed_for_atm_GeV": mD ** 2 / (SQRT_DM2_ATM_EV * 1e-9)}
