"""C4-equivariant (character-valued) index of the locked conoid.

Exploratory: not part of the locked SAM-3 core.

The locked theorem (docs 44, 46; core paper) is that the ordinary APS index
of the untwisted Dirac operator on the truncated conoid, with a product
collar and the bounding spin structure, is 0.  The complete surface has
total curvature ∫K = −2π, and the tip is a geodesic boundary circle of
length 8ℓ₀ with four metric-degeneracy points (the nodes).

The conoid admits a C4 isometry, generated by v ↦ v+π/2, which preserves
the metric.  If that action were not free, an equivariant or orbifold
index theorem could in principle assign nonzero Lefschetz numbers to the
fixed-point set and, after a Fourier decomposition into characters of C4,
a nonzero index in one isotypic component.

This module checks the fixed-point question intrinsically (not in the
R³ embedding, where the four nodes coincide at the origin).  The
isometry is the translation (u, v) ↦ (u, v + k π/2) on the (u, v)
cylinder, with v ∼ v+2π.  That translation has a fixed point if and
only if k ≡ 0 (mod 4).  The four nodes, at u = 0 and
v = π/4 + m π/2, are cycled by the generator, so none is fixed either.

A free action of a finite group, together with the vanishing of the
ordinary index, implies that every character-valued index vanishes:
the Lefschetz number of each non-identity element is zero (empty fixed
set), and the identity contributes the ordinary index 0.  Equivalently,
the index on the quotient is 0.  This is not a numerical index
computation; it is the standard character formula plus the locked
theorem Ind = 0 plus freeness, which is checked below.

Verdict: the C4-equivariant index does not produce three generations.
"""

from __future__ import annotations

import math
from typing import Dict, List, Tuple

# Nodes of metric degeneracy on the tip circle u=0:  cos(2v) = 0.
NODE_V = tuple(math.pi / 4.0 + m * math.pi / 2.0 for m in range(4))


def isometry(v: float, k: int) -> float:
    """Image of the angular coordinate under the k-th power of the generator."""
    return v + k * math.pi / 2.0


def angle_difference(a: float, b: float) -> float:
    """Signed difference a−b, reduced to (−π, π]."""
    d = (a - b + math.pi) % (2.0 * math.pi) - math.pi
    return d


def has_fixed_point(k: int, n_u: int = 20, n_v: int = 80) -> bool:
    """Intrinsic fixed-point test for g^k, including the tip u=0.

    A point (u, v) is fixed iff v ≡ v + k π/2  (mod 2π), independently of
    u.  The only solutions occur when k is a multiple of 4.  The grid
    test below is a numerical confirmation, not the source of the result.
    """
    if k % 4 == 0:
        return True  # the identity, every point is fixed
    # Analytic condition: k π/2 ≡ 0 (mod 2π) ⇔ k ≡ 0 (mod 4), already false.
    # Check a grid anyway, including nodes.
    us = [0.0] + [0.1 * i for i in range(1, n_u + 1)]
    vs = [2.0 * math.pi * j / n_v for j in range(n_v)] + list(NODE_V)
    for u in us:
        for v in vs:
            if abs(angle_difference(isometry(v, k), v)) < 1e-12:
                return True
    return False


def nodes_cycled_by_generator() -> List[int]:
    """For each node, the index of its image under v ↦ v+π/2, among the four nodes."""
    images = []
    for v in NODE_V:
        w = isometry(v, 1)
        dists = [abs(angle_difference(w, n)) for n in NODE_V]
        images.append(int(min(range(4), key=lambda i: dists[i])))
    return images


def character_indices() -> Dict[str, int]:
    """Character-valued index, from Lefschetz + locked ordinary index 0.

    L(g^k) = 0 for k = 0,1,2,3  (k=0 is the ordinary index).
    The index in the character η is (1/4) ∑_k η-bar^k L(g^k) = 0.
    """
    lefshetz = {0: 0, 1: 0, 2: 0, 3: 0}  # k=0: locked APS index
    out = {}
    for name, eta in (("+1", 1), ("+i", 1j), ("-1", -1), ("-i", -1j)):
        acc = 0j
        for k, L in lefshetz.items():
            acc += (eta.conjugate() ** k) * L
        out[name] = int(round(acc.real / 4.0))
    return out


def report() -> Dict[str, object]:
    fixed = {f"k={k}": has_fixed_point(k) for k in range(4)}
    cycle = nodes_cycled_by_generator()
    return {
        "action": "v |-> v + k pi/2,  u unchanged,  v ~ v+2 pi",
        "identity_has_fixed_points": fixed["k=0"],
        "nonidentity_has_fixed_points": any(fixed[f"k={k}"] for k in (1, 2, 3)),
        "fixed_point_table": fixed,
        "nodes_v": list(NODE_V),
        "nodes_cycled_to": cycle,
        "generator_acts_as_a_4-cycle_on_nodes": cycle == [1, 2, 3, 0] or set(cycle) == {0, 1, 2, 3},
        "ordinary_APS_index_locked": 0,
        "character_indices": character_indices(),
        "verdict": (
            "The C4 action is free on the truncated and complete conoid "
            "(the four nodes are cycled, not fixed).  Together with the "
            "locked ordinary index 0, every character-valued index is 0.  "
            "This does not produce three generations."
        ),
    }
